package com.minke.mallmanagement.chat.model;

/**
 * 智能客服的意图枚举。
 *
 * <p>⚠️ 只做**规则匹配**，不接任何远端模型：本仓没有 LLM 依赖，短文本、领域固定的场景
 * 也不需要为一句「查订单」引入网络往返与不可控延迟。
 *
 * <p>判定顺序见 {@code ChatIntentRecognizer}：售后 &gt; 订单 &gt; 秒杀 &gt; 开店 &gt; 身份自述
 * &gt; 问候 &gt; 帮助 &gt; 兜底。售后排在订单前面，是因为「查订单的退款进度」同时命中两套
 * 关键词，而用户真正想知道的是退款；秒杀排在开店前面，是因为「上架到秒杀」也含「上架」。
 */
public enum ChatIntent {

    /** 查订单状态（最新一笔 / 指定单号 / 最近若干笔）。 */
    ORDER_QUERY,

    /** 查售后 / 退款进度。 */
    REFUND_QUERY,

    /**
     * 查评论 / 评价（2026-10-22「业务工具挂载」）：
     * 商家看自己商品收到的评论与回复状态，客户看自己发过的评论。
     *
     * <p>⚠️ 与 {@link #NAVIGATE} 的边界：平台**没有**独立的评价管理页，
     * 「我要看评论」问的是**内容本身**（有没有人评、回了没有）⇒ 本意图；
     * 只有用户明确说「打开评价页」这类不存在的页面时才走 NAVIGATE 的兜底话术。
     */
    COMMENT_QUERY,

    /**
     * 查商品本身（2026-10-22「商品查询」修复）：用户问某个商品的价格、详情、参数、库存，
     * 或者直接贴出商品名 / 商品编号（如 {@code 222:ij-555}）。
     *
     * <p>⚠️ 与 {@link #NAVIGATE} 的边界：「怎么上架 / 改价 / 管理商品」是去某个页面办事
     * ⇒ NAVIGATE；问「这个商品多少钱 / 详细数据」才是本意图。商品编号**不是**订单号：
     * 带冒号的编号（{@code 222:ij-555}）必须原样进 {@code goodsKeyword}，不能进
     * {@code orderId}。
     */
    GOODS_QUERY,

    /** 怎么开店 / 商家入驻 —— 回复里带一个触发前端漫游的 action。 */
    OPEN_STORE,

    /** 报名秒杀 / 参加平台活动 —— 只导航 + 六态分支，不猜商品与价格（N3 / Q5=A）。 */
    ADD_TO_SECKILL,

    /**
     * 页面导航 · **默认模式**（2026-10-22 交互纠偏）：用户问「怎么去 / 怎么申请 / 怎么上架」
     * 时给【开始引导】，前端从**当前页**跑 BFS 逐步高亮 —— 绝不替用户瞬移。
     */
    GUIDE_NAVIGATION,

    /**
     * 页面导航 · **直达模式**：只有用户**明确说**「直接带我去 / 我要去 / 马上打开」才给
     * 【一键直达】；前端忽略中间节点，直接 {@code router.push(targetPath)}。
     *
     * <p>判据是确定性的正则（{@code ChatAgentService.DIRECT_NAV}），不依赖大模型 ——
     * 模型把「直接带我去」判成 GUIDE 也不会让用户多点两次。
     */
    DIRECT_NAVIGATION,

    /**
     * @deprecated 旧的单值导航意图（2026-10-22 拆成 GUIDE / DIRECT）。保留常量只为兼容
     * 旧工具注解 / 旧调用点：模型或规则仍可能给出它，编排层一律归一为
     * {@link #GUIDE_NAVIGATION}（默认引导）。
     */
    @Deprecated
    NAVIGATE,

    /** 用户自述身份（「我是商家」）—— 用于对照系统解析结果，不盲信（增量-A 规则 2）。 */
    IDENTITY_CLAIM,

    /** 问候。 */
    GREETING,

    /** 「你能做什么」类。 */
    HELP,

    /** 规则没命中，但命中了 FAQ 知识库（增量「轻量知识库」）。 */
    FAQ,

    /** 规则都没命中、FAQ 也没命中。 */
    UNKNOWN
}
